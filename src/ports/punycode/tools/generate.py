#!/usr/bin/env python3
"""Generate portable Oberon Unicode 16.0 tables from pinned IDNA data."""

import ast
import bisect
import hashlib
from pathlib import Path
import unicodedata as ucd

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "idnadata.py": "486f2385a184e778a20fa078f69b76a704effd4bc295c89613e379e28476a785",
    "uts46data.py": "1fd277e55903d05f4bf6628eaa378d19dd80f956ba1653e8cfa273e0aee1fa9b",
}


def table_file(name):
    data = (ROOT / "data" / name).read_bytes()
    assert hashlib.sha256(data).hexdigest() == SOURCES[name], name
    return ast.parse(data)


def emit(module, constants, words, procedures):
    # Hexadecimal strings store the table as constant Oberon data.
    # Each constant holds 128 unsigned 24-bit words, below VOC's literal limit.
    assert all(0 <= word < 1 << 24 for word in words)
    chunks = ["".join(f"{w:06X}" for w in words[i:i+128]) for i in range(0, len(words), 128)]
    lines = [f"MODULE {module};", "", "(* Generated by tools/generate.py; Unicode 16.0.0. See NOTICE. *)", "", "CONST"]
    lines += [f"  {key}* = {value};" for key, value in constants.items()]
    lines += [f'  d{i} = "{chunk}";' for i, chunk in enumerate(chunks)]
    lines += ["", "PROCEDURE At(text: ARRAY OF CHAR; offset: LONGINT): CHAR;",
              "BEGIN RETURN text[offset]", "END At;"]
    groups = (len(chunks)+127)//128
    for group in range(groups):
        lines += ["", f"PROCEDURE Byte{group}(block, offset: LONGINT): CHAR;", "BEGIN", "  CASE block OF"]
        lines += [f"  | {i%128}: RETURN At(d{i}, offset)" for i in range(group*128, min(len(chunks), (group+1)*128))]
        lines += ["  ELSE HALT(99)", "  END", f"END Byte{group};"]
    lines += ["", "PROCEDURE Word*(index: LONGINT): LONGINT;", "  VAR offset, i, value, digit, block: LONGINT; byte: CHAR;", "BEGIN", f"  ASSERT((index >= 0) & (index < {len(words)}));", "  offset := index MOD 128 * 6; value := 0; block := index DIV 128;", "  FOR i := 0 TO 5 DO", "    CASE block DIV 128 OF"]
    lines += [f"    | {i}: byte := Byte{i}(block MOD 128, offset+i)" for i in range(groups)]
    lines += ["    ELSE HALT(99)", "    END;", '    digit := ORD(byte)-ORD("0"); IF digit > 9 THEN DEC(digit, 7) END;', "    value := value*16+digit", "  END;", "  RETURN value", "END Word;", "", procedures, "", f"END {module}.", ""]
    (ROOT / (module + ".Mod")).write_text("\n".join(lines))


def main():
    assert ucd.unidata_version == "16.0.0", "Use Python with Unicode 16.0.0 (Python 3.14)."
    data = {}
    for node in table_file("idnadata.py").body:
        if isinstance(node, ast.Assign):
            data[node.targets[0].id] = ast.literal_eval(node.value)
    rows = []
    for node in table_file("uts46data.py").body:
        if isinstance(node, ast.FunctionDef) and node.name.startswith("_seg_"):
            rows.extend(ast.literal_eval(node.body[0].value))
    assert rows == sorted(rows) and len(rows) > 8000
    words, pool = [], []
    for row in rows:
        replacement = [ord(c) for c in row[2]] if len(row) == 3 else []
        words.extend([row[0], ord(row[1]), len(pool), len(replacement)])
        pool.extend(replacement)
    emit("IDNAMapping", {"count": len(rows), "pool": len(words)}, words + pool, """
PROCEDURE Find*(character: LONGINT): LONGINT;
  VAR lo, hi, mid: LONGINT;
BEGIN
  lo := 0; hi := count;
  WHILE lo+1 < hi DO
    mid := (lo+hi) DIV 2;
    IF Word(mid*4) <= character THEN lo := mid ELSE hi := mid END
  END;
  RETURN lo*4
END Find;""")

    def contains(character, ranges):
        key = character << 32
        index = bisect.bisect_left(ranges, key)
        if index < len(ranges) and ranges[index] >> 32 == character:
            return True
        return index > 0 and character < ranges[index-1] & 0xFFFFFFFF

    directions = ["", "L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON", "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
    directions = {value: index for index, value in enumerate(directions)}
    joining = {ord(c): i for i, c in enumerate("ULRDT")}
    script_names = ["Greek", "Hebrew", "Hiragana", "Katakana", "Han"]
    properties = []; previous = None
    for character in range(0x110000):
        text = chr(character)
        valid = 0
        for i, key in enumerate(["PVALID", "CONTEXTJ", "CONTEXTO"], 1):
            if contains(character, data["codepoint_classes"][key]):
                valid = i; break
        scripts = sum(1 << (16+i) for i, key in enumerate(script_names) if contains(character, data["scripts"][key]))
        value = ucd.combining(text) + directions[ucd.bidirectional(text)]*256 + (ucd.category(text).startswith("M"))*8192 + valid*16384 + scripts + joining.get(data["joining_types"].get(character), 0)*2097152
        if value != previous:
            properties.extend([character, value]); previous = value
    decomp, decomposition_pool, composition = [], [], []
    for character in range(0x110000):
        if 0xAC00 <= character < 0xD7A4:
            continue  # Hangul decomposition/composition is algorithmic.
        text = chr(character)
        description = ucd.decomposition(text)
        if description and not description.startswith("<"):
            parts = [int(x, 16) for x in description.split()]
            full = [ord(c) for c in ucd.normalize("NFD", text)]
            decomp.extend([character, len(decomposition_pool), len(full)])
            decomposition_pool.extend(full)
            if len(parts) == 2 and ucd.normalize("NFC", "".join(map(chr, parts))) == text:
                composition.append((*parts, character))
    composition.sort()
    constants = {"propertiesCount": len(properties)//2, "decompCount": len(decomp)//3, "decompBase": len(properties), "decompPool": len(properties)+len(decomp), "compCount": len(composition), "compBase": len(properties)+len(decomp)+len(decomposition_pool)}
    words = properties + decomp + decomposition_pool + [v for row in composition for v in row]
    emit("IDNAData", constants, words, """
PROCEDURE Properties*(character: LONGINT): LONGINT;
  VAR lo, hi, mid: LONGINT;
BEGIN
  lo := 0; hi := propertiesCount;
  WHILE lo+1 < hi DO
    mid := (lo+hi) DIV 2;
    IF Word(mid*2) <= character THEN lo := mid ELSE hi := mid END
  END;
  RETURN Word(lo*2+1)
END Properties;

PROCEDURE Combining*(character: LONGINT): LONGINT;
BEGIN RETURN Properties(character) MOD 256
END Combining;

PROCEDURE Decomposition*(character: LONGINT; VAR offset, count: LONGINT);
  VAR lo, hi, mid, value: LONGINT;
BEGIN
  lo := 0; hi := decompCount; count := 0; offset := 0;
  WHILE lo < hi DO
    mid := (lo+hi) DIV 2; value := Word(decompBase+mid*3);
    IF value < character THEN lo := mid+1
    ELSIF value > character THEN hi := mid
    ELSE offset := decompPool+Word(decompBase+mid*3+1); count := Word(decompBase+mid*3+2); RETURN
    END
  END
END Decomposition;

PROCEDURE Compose*(first, second: LONGINT): LONGINT;
  VAR lo, hi, mid, a, b: LONGINT;
BEGIN
  IF (first >= 1100H) & (first < 1113H) & (second >= 1161H) & (second < 1176H) THEN
    RETURN 0AC00H+((first-1100H)*21+second-1161H)*28
  END;
  IF (first >= 0AC00H) & (first < 0D7A4H) & ((first-0AC00H) MOD 28 = 0) &
     (second > 11A7H) & (second < 11C3H) THEN RETURN first+second-11A7H END;
  lo := 0; hi := compCount;
  WHILE lo < hi DO
    mid := (lo+hi) DIV 2; a := Word(compBase+mid*3); b := Word(compBase+mid*3+1);
    IF (a < first) OR ((a = first) & (b < second)) THEN lo := mid+1
    ELSIF (a > first) OR ((a = first) & (b > second)) THEN hi := mid
    ELSE RETURN Word(compBase+mid*3+2)
    END
  END;
  RETURN -1
END Compose;""")
    print("Generated Unicode 16.0 tables:", len(rows), "mapping rows;", constants)


if __name__ == "__main__":
    main()
